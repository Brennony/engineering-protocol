# Basic Calculator Functions
def addition(num1, num2):
    return num1 + num2

def subtraction(num1, num2):
    return num1 - num2 

def multiplication(num1, num2):
    return num1 * num2

def division(num1, num2):
    return num1 / num2

def remainder(num1, num2):
    return num1 % num2

def power(num1, num2):
    return num1 ** num2